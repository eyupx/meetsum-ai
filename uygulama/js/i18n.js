function getCurrentLang() {
  return localStorage.getItem('meetsum_lang') || 'tr';
}

function t(key) {
  const lang = getCurrentLang();
  return (LANGS[lang] && LANGS[lang][key]) || (LANGS['tr'] && LANGS['tr'][key]) || key;
}

function firebaseErrorToMessage(code) {
  const lang = getCurrentLang();
  const map = {
    'auth/email-already-in-use': lang === 'tr' ? LANGS.tr.err_email_in_use : LANGS.en.err_email_in_use,
    'auth/weak-password': lang === 'tr' ? LANGS.tr.err_weak_password : LANGS.en.err_weak_password,
    'auth/user-not-found': lang === 'tr' ? LANGS.tr.err_user_not_found : LANGS.en.err_user_not_found,
    'auth/wrong-password': lang === 'tr' ? LANGS.tr.err_wrong_password : LANGS.en.err_wrong_password,
    'auth/invalid-email': lang === 'tr' ? LANGS.tr.err_invalid_email : LANGS.en.err_invalid_email,
    'auth/invalid-credential': lang === 'tr' ? LANGS.tr.err_wrong_password : LANGS.en.err_wrong_password
  };
  return map[code] || (lang === 'tr' ? LANGS.tr.err_generic : LANGS.en.err_generic);
}
